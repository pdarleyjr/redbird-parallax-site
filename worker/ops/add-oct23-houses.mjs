// One-off production sync (2026-10-28): publish the six houses from the Oct 23 export (#47-#52) and register their built-in icons.
//   node ops/add-oct23-houses.mjs            read production D1 (read-only), print the plan, write ops/oct23-houses.sql
//   node ops/add-oct23-houses.mjs --apply    also execute that SQL against production
// Needs CLOUDFLARE_API_TOKEN in the environment. It builds the next snapshot from what production holds NOW (so admin edits made since the
// seed are kept), with a strictly increasing version, and refuses to run if any of the new ids, numbers or addresses already exist.
import { execFileSync } from 'node:child_process';
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildSnapshot, etagFor } from '../src/lib/snapshot.js';
import { normalizeAddress } from '../../shared/address.mjs';

const here = path.dirname(fileURLToPath(import.meta.url));
const repo = path.resolve(here, '../..');
const WRANGLER = path.join(here, '../node_modules/wrangler/bin/wrangler.js');
const NOW = new Date().toISOString();
const q = v => (v == null ? 'NULL' : typeof v === 'number' ? String(v) : `'${String(v).replaceAll("'", "''")}'`);

const d1 = sql => {
  const out = execFileSync(process.execPath, [WRANGLER, 'd1', 'execute', 'redbird-trails', '--remote', '--json', '--command', sql], { cwd: path.join(here, '..'), encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 });
  return JSON.parse(out)[0].results;
};

const decisions = JSON.parse(await readFile(path.join(repo, 'data/reconcile/2026-10-23.decisions.json'), 'utf8'));
const flyer = new Map(JSON.parse(await readFile(path.join(repo, 'tools/flyer-map/houses.json'), 'utf8')).map(h => [h.n, h]));
const catalog = JSON.parse(await readFile(path.join(repo, 'data/icons.json'), 'utf8')).icons;

const event = d1("SELECT * FROM events WHERE id = 'halloween-2026'")[0];
const houses = d1("SELECT * FROM houses WHERE event_id = 'halloween-2026'");
const version = d1("SELECT MAX(version) AS v FROM snapshots WHERE event_id = 'halloween-2026'")[0].v;
const icons = d1('SELECT key FROM icons').map(r => r.key);
console.log(`production: ${houses.length} houses, snapshot v${version}, ${icons.length} icons`);

const fresh = decisions.approvedNew.map(n => {
  const a = normalizeAddress(n.address), pin = flyer.get(n.mapNumber);
  if (!pin) throw new Error(`no pin for #${n.mapNumber} in tools/flyer-map/houses.json`);
  return { id: n.id, event_id: event.id, map_number: n.mapNumber, name: n.name, address_display: a.display, address_key: a.key, description: null, icon: n.icon, lat: pin.lat, lng: pin.lng,
    location_status: 'suggested', location_source: 'osm-building', status: 'published', version: 1, created_at: NOW, updated_at: NOW, updated_by: 'oct23-import' };
});
for (const h of fresh) {
  if (houses.some(x => x.id === h.id || x.map_number === h.map_number || (x.address_key === h.address_key && x.status !== 'archived'))) throw new Error(`${h.id} (#${h.map_number}, ${h.address_display}) already exists in production; refusing`);
  if (!catalog.some(i => i.key === h.icon)) throw new Error(`icon ${h.icon} is not in data/icons.json`);
}

const snapshot = buildSnapshot({ event, houses: [...houses, ...fresh.map(h => ({ ...h }))], version: version + 1, now: NOW, boundary: JSON.parse(event.boundary_geojson) });
if (snapshot.houses.length !== houses.filter(h => h.status === 'published').length + fresh.length) throw new Error('snapshot house count is off');
const payload = JSON.stringify(snapshot);

const lines = [`-- GENERATED by ops/add-oct23-houses.mjs on ${NOW}. Publishes #47-#52 and registers their built-in icons. Snapshot v${snapshot.version}.`];
for (const i of catalog.filter(i => !icons.includes(i.key))) lines.push(`INSERT INTO icons (key, label, source, status, created_at, created_by) VALUES (${[i.key, i.label.slice(0, 40), 'builtin', 'active', NOW, 'oct23-import'].map(q).join(', ')});`);
for (const h of fresh) lines.push(`INSERT INTO houses (id, event_id, map_number, name, address_display, address_key, description, icon, lat, lng, location_status, location_source, status, version, created_at, updated_at, updated_by) VALUES (${[h.id, h.event_id, h.map_number, h.name, h.address_display, h.address_key, h.description, h.icon, h.lat, h.lng, h.location_status, h.location_source, h.status, h.version, h.created_at, h.updated_at, h.updated_by].map(q).join(', ')});`);
for (const h of fresh) lines.push(`INSERT INTO audit_log (at, actor, action, entity, entity_id, after_json) VALUES (${[NOW, 'oct23-import', 'house.create', 'house', h.id, JSON.stringify({ name: h.name, address: h.address_display, icon: h.icon, status: 'published' })].map(q).join(', ')});`);
lines.push(`INSERT INTO snapshots (event_id, version, created_at, created_by, payload_json, etag) VALUES (${[event.id, snapshot.version, NOW, 'oct23-import', payload, await etagFor(payload)].map(q).join(', ')});`);
const out = path.join(here, 'oct23-houses.sql');
await writeFile(out, lines.join('\n') + '\n');
console.log(`plan: +${fresh.length} houses (${fresh.map(h => '#' + h.map_number).join(', ')}), +${lines.filter(l => l.startsWith('INSERT INTO icons')).length} icons, snapshot v${snapshot.version} with ${snapshot.houses.length} houses -> ${out}`);

if (process.argv.includes('--apply')) {
  execFileSync(process.execPath, [WRANGLER, 'd1', 'execute', 'redbird-trails', '--remote', '--file', out], { cwd: path.join(here, '..'), stdio: 'inherit' });
  const after = d1("SELECT (SELECT COUNT(*) FROM houses WHERE event_id = 'halloween-2026' AND status = 'published') AS published, (SELECT MAX(version) FROM snapshots WHERE event_id = 'halloween-2026') AS version");
  console.log('production now:', JSON.stringify(after[0]));
}
