// Generate sw.js (strategies per 05-TECH-SPEC 5.9). The version covers app code/assets only, never data.
import { readdir, readFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import path from 'node:path';

async function walk(dir, base = dir) {
  const out = [];
  let entries = [];
  try { entries = await readdir(dir, { withFileTypes: true }); } catch { return out; }
  for (const entry of entries) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) out.push(...await walk(full, base)); else out.push(path.relative(base, full).split(path.sep).join('/'));
  }
  return out.sort();
}

export async function mapFiles(root) {
  const files = (await walk(path.join(root, 'assets/map'))).filter(f => !f.startsWith('print-base') && f !== 'manifest.json');
  return files.map(f => `assets/map/${f}`);
}

export async function mapHash(root, files) {
  const hash = createHash('sha256');
  for (const f of files) hash.update(f).update(/\.(json)$/.test(f) ? Buffer.from((await readFile(path.join(root, f), 'utf8')).replace(/\r\n/g, '\n')) : await readFile(path.join(root, f)));
  return hash.digest('hex').slice(0, 10);
}

export async function buildServiceWorker({ root, outputs, hash, site }) {
  const pages = [...outputs.keys()].filter(k => k.endsWith('.html') || k === 'manifest.webmanifest' || k === 'assets/js/legacy-redirect.js');
  const shellDirs = ['shared', 'assets/css', 'assets/js', 'assets/fonts', 'assets/app', 'assets/img/markers', 'assets/img/optimized', 'assets/img/christmas'];
  const shell = [...pages];
  for (const dir of shellDirs) shell.push(...(await walk(path.join(root, dir))).map(f => `${dir}/${f}`));
  shell.push('data/icons.json', ...(await walk(path.join(root, 'assets/map'))).filter(f => f.startsWith('print-base')).map(f => `assets/map/${f}`));
  const data = ['data/site.json', ...(site.events.map(e => e.snapshot).filter(Boolean))];
  const maps = await mapFiles(root);
  outputs.set('assets/map/manifest.json', JSON.stringify(maps) + '\n');
  const api = site.api?.publicBase ? new URL(site.api.publicBase).origin : null;
  return `// GENERATED by scripts/build.mjs. Do not edit. Replace with scripts/sw-rollback.mjs output to roll back.
const VERSION = ${JSON.stringify(hash.slice(0, 12))};
const SHELL = 'rbht-shell-' + VERSION;
const MAP = 'rbht-map-' + ${JSON.stringify(await mapHash(root, maps))};
const DATA = 'rbht-data';
const API = ${JSON.stringify(api)};
const PRECACHE = ${JSON.stringify([...new Set(shell)].sort())};
const DATA_URLS = ${JSON.stringify(data)};
const scope = self.registration.scope;
const abs = u => new URL(u, scope).href;

self.addEventListener('install', event => {
  event.waitUntil((async () => {
    const shell = await caches.open(SHELL);
    await Promise.all(PRECACHE.map(async u => { try { await shell.add(new Request(abs(u), { cache: 'reload' })); } catch (e) { /* optional files may be absent */ } }));
    const data = await caches.open(DATA);
    await Promise.all(DATA_URLS.map(async u => { try { await data.add(new Request(abs(u), { cache: 'reload' })); } catch (e) { /* offline install */ } }));
  })());
});

self.addEventListener('activate', event => {
  event.waitUntil((async () => {
    const keep = new Set([SHELL, MAP, DATA]);
    for (const key of await caches.keys()) if (key.startsWith('rbht-') && !keep.has(key)) await caches.delete(key);
    await self.clients.claim();
  })());
});

self.addEventListener('message', event => {
  if (event.data?.type === 'SKIP_WAITING') self.skipWaiting();
  if (event.data?.type === 'warm-map') event.waitUntil(warmMap());
  if (event.data?.type === 'GET_VERSION') event.source?.postMessage({ type: 'VERSION', version: VERSION });
});

async function warmMap() {
  const cache = await caches.open(MAP);
  try {
    const list = await (await fetch(abs('assets/map/manifest.json'), { cache: 'no-cache' })).json();
    for (const u of list) { if (!(await cache.match(abs(u)))) { try { await cache.add(abs(u)); } catch (e) { /* skip */ } } }
  } catch (e) { /* offline */ }
}

const withTimeout = (promise, ms) => Promise.race([promise, new Promise((_, reject) => setTimeout(() => reject(new Error('timeout')), ms))]);

// Network first. A failed fetch or a non-OK response falls back to the cached copy when there is one. Cache writes finish via waitUntil.
async function networkFirst(event, request, cacheName, ms, fallback) {
  const cache = await caches.open(cacheName);
  const cached = () => cache.match(request, { ignoreSearch: true });
  try {
    const response = await withTimeout(fetch(request), ms);
    if (response.ok) { event.waitUntil(cache.put(request, response.clone())); return response; }
    return (await cached()) || response;
  } catch (e) {
    return (await cached()) || (fallback ? fallback() : Response.error());
  }
}

async function cacheFirst(event, request, cacheName) {
  const cache = await caches.open(cacheName);
  const hit = await cache.match(request, { ignoreSearch: true });
  if (hit) return hit;
  const response = await fetch(request);
  if (response.ok) event.waitUntil(cache.put(request, response.clone()));
  return response;
}

// "/halloween/" and "/?source=pwa" are stored as halloween/index.html and index.html.
const pageKey = url => { const p = url.pathname.slice(new URL(scope).pathname.length); return abs(p === '' || p.endsWith('/') ? p + 'index.html' : p); };

self.addEventListener('fetch', event => {
  const request = event.request;
  if (request.method !== 'GET') return;
  const url = new URL(request.url);
  const sameOrigin = url.origin === self.location.origin;
  if (!sameOrigin && !(API && url.origin === API)) return;
  const path = sameOrigin ? url.href.slice(scope.length) : '';
  if (!sameOrigin) {
    event.respondWith(networkFirst(event, request, DATA, 4000, () => Response.error()));
  } else if (request.mode === 'navigate') {
    event.respondWith((async () => {
      const shell = await caches.open(SHELL);
      try {
        const response = await withTimeout(fetch(request), 3000);
        if (response.ok) { event.waitUntil(shell.put(pageKey(url), response.clone())); return response; }
        return (await shell.match(pageKey(url))) || response;
      } catch (e) {
        return (await shell.match(pageKey(url))) || (await shell.match(abs('offline.html'))) || Response.error();
      }
    })());
  } else if (/\\.public\\.json$/.test(path) || path === 'data/site.json') {
    event.respondWith(networkFirst(event, request, DATA, 4000, () => Response.error()));
  } else if (path.startsWith('assets/map/print-base')) {
    event.respondWith(cacheFirst(event, request, SHELL));
  } else if (path.startsWith('assets/map/')) {
    event.respondWith(cacheFirst(event, request, MAP));
  } else {
    event.respondWith(cacheFirst(event, request, SHELL));
  }
});
`;
}
