// Generate worker/migrations/0002_seed_2026.sql from the public snapshot (no personal data exists in it).
//   node scripts/emit-seed.mjs          write the file
//   node scripts/emit-seed.mjs --check  fail if it is stale
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { makeSnapshot, flyerPositions, root } from './make-snapshot.mjs';
import { normalizeAddress } from '../shared/address.mjs';

const q = v => (v == null ? 'NULL' : typeof v === 'number' ? String(v) : `'${String(v).replaceAll("'", "''")}'`);
const NOW = '2026-10-16T12:00:00Z';

export async function seedSQL() {
  const snapshot = await makeSnapshot();
  const sources = await flyerPositions();
  const site = JSON.parse(await readFile(path.join(root, 'data/site.json'), 'utf8'));
  const boundary = JSON.stringify(snapshot.boundary), extent = JSON.stringify(snapshot.printExtent);
  const lines = ['-- GENERATED by scripts/emit-seed.mjs from data/halloween-2026.public.json. Do not edit.'];
  for (const ev of site.events) {
    const details = ev.kind === 'christmas' ? JSON.stringify({ art: 'christmas' }) : JSON.stringify({ art: 'halloween' });
    lines.push(`INSERT INTO events (id, kind, year, slug, title, status, date, start_time, end_time, time_zone, details_json, boundary_geojson, print_extent_json, updated_at, updated_by) VALUES (${[ev.id, ev.kind, ev.year, ev.slug, ev.title, ev.status, ev.date, ev.start, ev.end, ev.timeZone, details, boundary, extent, NOW, 'seed'].map(q).join(', ')});`);
  }
  for (const h of snapshot.houses) {
    const a = normalizeAddress(h.address);
    const loc = h.location === 'none' ? 'none' : h.location === 'verified' ? 'verified' : 'suggested';
    lines.push(`INSERT INTO houses (id, event_id, map_number, name, address_display, address_key, description, icon, lat, lng, location_status, location_source, status, version, created_at, updated_at, updated_by) VALUES (${[h.id, snapshot.eventId, h.mapNumber, h.name, a.display, a.key, h.description, h.icon, h.lat, h.lng, loc, h.location === 'none' ? null : (sources.get(h.mapNumber)?.source || 'census'), 'published', 1, NOW, NOW, 'seed'].map(q).join(', ')});`);
  }
  const first = { ...snapshot, version: snapshot.version + 1 };
  lines.push(`INSERT INTO snapshots (event_id, version, created_at, created_by, payload_json, etag) VALUES (${[snapshot.eventId, first.version, NOW, 'seed', JSON.stringify(first), `seed-${first.version}`].map(q).join(', ')});`);
  lines.push(`INSERT INTO audit_log (at, actor, action, entity, entity_id) VALUES (${[NOW, 'seed', 'seed.import', 'event', snapshot.eventId].map(q).join(', ')});`);
  return lines.join('\n') + '\n';
}

/** One-off sync for a production database that is ahead of the seed (currently at snapshot version `from`): update every house to the
 *  current snapshot and add snapshot version from+1. Not a migration. */
export async function deltaSQL(from = 3) {
  const snapshot = await makeSnapshot();
  const sources = await flyerPositions();
  const lines = [`-- GENERATED by scripts/emit-seed.mjs --delta ${from}. One-off: bring houses to the current snapshot (positions, icons, names) and add version ${from + 1}.`];
  for (const h of snapshot.houses) {
    const a = normalizeAddress(h.address);
    const loc = h.location === 'none' ? 'none' : h.location === 'verified' ? 'verified' : 'suggested';
    const src = h.location === 'none' ? null : (sources.get(h.mapNumber)?.source || 'census');
    lines.push(`UPDATE houses SET name = ${q(h.name)}, address_display = ${q(a.display)}, icon = ${q(h.icon)}, lat = ${q(h.lat)}, lng = ${q(h.lng)}, location_status = ${q(loc)}, location_source = ${q(src)}, version = version + 1, updated_at = ${q(NOW)}, updated_by = 'seed' WHERE id = ${q(h.id)};`);
  }
  const next = { ...snapshot, version: from + 1 };
  lines.push(`INSERT INTO snapshots (event_id, version, created_at, created_by, payload_json, etag) VALUES (${[snapshot.eventId, from + 1, NOW, 'seed', JSON.stringify(next), `seed-${from + 1}`].map(q).join(', ')});`);
  lines.push(`INSERT INTO audit_log (at, actor, action, entity, entity_id) VALUES (${[NOW, 'seed', 'seed.sync', 'event', snapshot.eventId].map(q).join(', ')});`);
  return lines.join('\n') + '\n';
}
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  if (process.argv.includes('--delta')) { const from = Number(process.argv[process.argv.indexOf('--delta') + 1]) || 3; const out = path.join(root, `worker/ops/sync-to-v${from + 1}.sql`); await mkdir(path.dirname(out), { recursive: true }); await writeFile(out, await deltaSQL(from)); console.log('Delta SQL written.'); process.exit(0); }
  const file = path.join(root, 'worker/migrations/0002_seed_2026.sql');
  const sql = await seedSQL();
  if (process.argv.includes('--check')) {
    if (sql !== await readFile(file, 'utf8')) throw new Error('worker/migrations/0002_seed_2026.sql is stale. Run node scripts/emit-seed.mjs');
    console.log('Seed SQL is current.');
  } else { await writeFile(file, sql); console.log('Seed SQL written.'); }
}
